def main():
    adapter = get_adapter()
    adapter.auth()

    # 防重复：项目表已有数据则跳过
    if adapter.list_rows("项目"):
        print("[skip] 项目 表已有数据，跳过演示数据写入。")
        print("        如需重建，请先清空 data/ 目录再运行本脚本。")
        return

    rows = build_rows()
    n = 0
    for table, data in rows:
        adapter.append_row(table, data)
        n += 1
    print(f"[ok] 已写入 {n} 条演示数据到本地 data/（共 {len(set(t for t, _ in rows))} 张表）。")
    print("      现在可以运行：python cockpit.py  生成驾驶舱 HTML。")


if __name__ == "__main__":
    main()
